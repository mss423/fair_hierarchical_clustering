"""Regenerate descriptive tables from saved results, never from hard-coded claims."""

from pathlib import Path
from collections import Counter
import json
import numpy as np
from fair_hc.plotting import load_results, mean_se, scenario


def fmt(values, digits=3):
    mean, se = mean_se(values)
    return f"{mean:.{digits}f} ± {se:.{digits}f}"


def main():
    rows, status = load_results("results")
    coverage = {}
    for path in sorted(Path("results").glob("*/manifest.json")):
        m = json.loads(path.read_text())
        coverage[path.parent.name] = dict(Counter(r["status"] for r in m["runs"].values()))
    lines = [
        "# Measured findings",
        "",
        "Generated by `python scripts/summarize_results.py` from saved run metrics. All ± values below are standard errors over ten independent seeds unless stated otherwise. Cluster observations are never treated as independent replications.",
        "",
        "## Coverage",
        "",
        "| Profile | Complete | Excluded | Other |",
        "|---|---:|---:|---:|",
    ]
    for profile, c in coverage.items():
        lines.append(
            f"| {profile} | {c.get('complete', 0)} | {c.get('excluded', 0)} | {sum(v for k, v in c.items() if k not in {'complete', 'excluded'})} |"
        )
    lines += [
        "",
        "Main: both datasets, n=128–8192 by powers of two, seeds 0–9, five methods. All main runs completed. Excluded runs are the explicitly invalid two-color h=4, k=2 setting. Synthetic coverage includes 2/3/4 colors, balanced/skewed groups, independent/correlated geometry, n=256/1024, and ten seeds.",
        "",
        "## Main study at 8,192 rows",
        "",
        "Raw numerical geometry; default h=16, k=2, epsilon=1/64. Cost ratios use each sample’s own average-linkage starting tree, not an optimum.",
        "",
        "| Dataset | Method | Cost / average | Max representation error | Nonsingleton clusters | Depth |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for dataset in ["adult", "bank"]:
        for method in ["average", "make_fair", "star", "splitting_only", "random_fold"]:
            selected = [
                r
                for r in rows
                if r["_profile"] == "main"
                and r["spec"]["dataset"] == dataset
                and r["spec"]["n"] == 8192
                and r["method"] == method
            ]
            vals = [
                fmt(
                    [r["metrics"][metric] for r in selected],
                    1 if metric in {"cluster_count", "depth"} else 3,
                )
                for metric in [
                    "cost_ratio_to_average",
                    "max_representation_error",
                    "cluster_count",
                    "depth",
                ]
            ]
            lines.append("| " + " | ".join([dataset, method] + vals) + " |")
    lines += [
        "",
        "MakeFair improves representation relative to the starting hierarchies on these samples, with substantial cost and resolution trade-offs. Random folding has similar cost but larger maximum representation error at n=8192. A star has zero representation error because its only nonsingleton cluster is the whole dataset; this is not a useful fairness victory on its own. There is no universal empirical superiority claim.",
        "",
        "## Runtime and resources",
        "",
        "| Dataset | Preprocessing (s) | Construction (s) | Transformation (s) | Evaluation (s) |",
        "|---|---:|---:|---:|---:|",
    ]
    for dataset in ["adult", "bank"]:
        selected = [
            r
            for r in rows
            if r["_profile"] == "main"
            and r["spec"]["dataset"] == dataset
            and r["spec"]["n"] == 8192
            and r["method"] == "make_fair"
        ]
        lines.append(
            "| "
            + dataset
            + " | "
            + " | ".join(
                fmt([r["times"][stage] for r in selected])
                for stage in ["preprocessing", "construction", "transformation", "evaluation"]
            )
            + " |"
        )
    peak = max(r["peak_process_rss_bytes"] for r in rows) / 2**30
    lines += [
        "",
        f"Maximum recorded process high-water RSS across the study: **{peak:.3f} GiB**, below the 8 GiB budget. This is process-lifetime peak RSS, not isolated per-run allocation. Runs were sequential. Preprocessing times cover sampling, scaling, provenance serialization, and geometry; one-time raw-file parsing is outside these stage timers. Shared preprocessing and construction times are charged to every method in runtime figures. These are local machine timings, not dedicated-machine performance guarantees.",
        "",
        "## Terminal cases and balance",
        "",
    ]
    fair = [r for r in rows if r["method"] == "make_fair"]
    reasons = Counter(t["reason"] for r in fair for t in r["diagnostics"]["terminal_cases"])
    lines += ["| Terminal reason | Cluster occurrences across MakeFair runs |", "|---|---:|"]
    lines += [f"| {reason} | {count} |" for reason, count in sorted(reasons.items())]
    exceeded = sum(
        any(f["imbalance"] > r["parameters"]["epsilon"] + 1e-12 for f in r["diagnostics"]["folds"])
        for r in fair
    )
    lines += [
        "",
        f"**{exceeded} of {len(fair)} MakeFair runs** had at least one fold whose measured size imbalance exceeded the original epsilon. This is consistent with additive errors accumulating under merges. Terminal counts above are descriptive counts, not independent statistical replications. Integer stalls can leave large terminal clusters. Inspect per-run diagnostics and the resolution figures before interpreting representation gains.",
        "",
        "## Sensitivity at 2,048 rows",
        "",
        "| Condition | Cost / average | Max representation error | Clusters |",
        "|---|---:|---:|---:|",
    ]
    selected = [
        r
        for r in rows
        if r["_profile"] == "sensitivity" and r["method"] == "make_fair" and r["spec"]["n"] == 2048
    ]
    for s in sorted(set(scenario(r) for r in selected)):
        sub = [r for r in selected if scenario(r) == s]
        lines.append(
            "| "
            + s
            + " | "
            + " | ".join(
                fmt([r["metrics"][metric] for r in sub])
                for metric in ["cost_ratio_to_average", "max_representation_error", "cluster_count"]
            )
            + " |"
        )
    lines += [
        "",
        "These conditions change feature scaling or the protected-group mapping. They are separately labeled measurements; rows need not coincide across different mappings, while all methods within a condition remain paired.",
        "",
        "## Multicolor examples at 1,024 rows",
        "",
        "| Condition | Cost / average | Max representation error | Clusters |",
        "|---|---:|---:|---:|",
    ]
    selected = [
        r
        for r in rows
        if r["_profile"] == "synthetic" and r["method"] == "make_fair" and r["spec"]["n"] == 1024
    ]
    for s in sorted(set(scenario(r) for r in selected)):
        sub = [r for r in selected if scenario(r) == s]
        lines.append(
            "| "
            + s
            + " | "
            + " | ".join(
                fmt([r["metrics"][metric] for r in sub])
                for metric in ["cost_ratio_to_average", "max_representation_error", "cluster_count"]
            )
            + " |"
        )
    lines += ["", "## Component checks", ""]
    path = Path("results/component-speedups.json")
    if path.exists():
        speed = json.loads(path.read_text())
        lines += [
            "| Equivalent computation, n=128 | Median reference / optimized time (5 seeds) |",
            "|---|---:|",
        ]
        for c in ["similarities", "average_linkage", "cost"]:
            values = [r["speedup"] for r in speed["rows"] if r["component"] == c and r["n"] == 128]
            lines.append(f"| {c} | {np.median(values):.1f}× |")
        lines += [
            "",
            "These small-case microbenchmarks compare identical similarity matrices, matching untied clades, and matching Dasgupta costs against intentionally simple independent Python references. They do not compare the corrected algorithm with an incorrect historical implementation, and do not establish large-n speedup factors. Raw timings, seeds, and dependency versions are saved in `results/component-speedups.json`.",
        ]
    lines += [
        "",
        "## Limits",
        "",
        "The corrected finite implementation is not a proof of the paper’s asymptotic guarantees. Group representation does not establish individual fairness or suitability for downstream decisions. Raw geometry is scale-sensitive, Adult uses complete cases from its training partition, and repeated seeds sample overlapping populations. Competitors beyond the specified controls are outside this study. No optimum or approximation ratio against an optimum is computed.",
        "",
    ]
    Path("docs/findings.md").write_text("\n".join(lines))
    Path("results/summary.json").write_text(
        json.dumps(
            {
                "status_counts": status,
                "coverage": coverage,
                "max_process_rss_gib": peak,
                "make_fair_runs": len(fair),
                "fold_tolerance_exceeding_runs": exceeded,
                "terminal_reasons": dict(reasons),
            },
            indent=2,
        )
        + "\n"
    )


if __name__ == "__main__":
    main()
